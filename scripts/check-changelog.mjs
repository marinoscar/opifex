#!/usr/bin/env node
/**
 * The CI changelog check (#312).
 *
 * #310 backfilled seven phases into CHANGELOG.md after the file went
 * ninety-four commits stale, and recorded the maintenance convention in the
 * file's own header. #312's point is that recording it changes nothing: the
 * mechanism that failed was "remember to update it", and a norm is that same
 * mechanism written down. Without a gate the file goes stale again, and the
 * only thing the written norm adds is that the second failure is legible.
 *
 * So, the rule, in full:
 *
 *   A pull request whose commits include a `feat` or a `fix` must touch
 *   CHANGELOG.md.
 *
 * ## What this does NOT check
 *
 * Whether the entry is any good. A whitespace edit satisfies this check, and
 * that is not a gap to be closed later — it is the boundary. Whether
 * CHANGELOG.md appears in a diff is mechanisable; whether the bullet explains
 * what the change means to somebody operating the system is not, and a check
 * that pretended otherwise would either reject honest entries or accept
 * dishonest ones. **The check enforces the habit. Review enforces the
 * content.** The failure message says so, because a check that overclaims
 * gets argued with instead of satisfied.
 *
 * ## There is no escape hatch, and that is the design
 *
 * #312 lists the options as no hatch, a label, or a marker in the PR body, and
 * notes that every hatch gets used routinely once it exists. The commit type
 * IS the hatch. A change that genuinely warrants no changelog line is not a
 * `feat` or a `fix` — it is a `chore`, a `refactor`, a `test` or a `docs`, and
 * this repository's commit vocabulary (CLAUDE.md, "Commit Message Standard")
 * already has the word for it. A second way to say "this does not count" would
 * let a real `feat` opt out, which is precisely the decay #310 documented.
 *
 * A consequence worth stating plainly: the PR that fixes the changelog is
 * exempt by construction, because a `docs`-only PR contains no `feat` or `fix`
 * commit. That is #312's fourth acceptance criterion, and it needs no special
 * case.
 *
 * ## Usage
 *
 *   node scripts/check-changelog.mjs --base <sha> --head <sha>
 *
 * Both are required. Nothing is inferred: guessing a base and getting it wrong
 * produces a check that quietly examines the wrong commits, which is the
 * silent-degradation failure scripts/check-provenance.mjs's header argues is
 * worse than having no check at all.
 */

import { fileURLToPath } from 'node:url';

import { commitsBetween, changedFiles } from './lib/git-range.mjs';

/** The file the convention is about. Repository-relative, as git reports it. */
const CHANGELOG = 'CHANGELOG.md';

/** The commit types that oblige an entry. Everything else is exempt. */
const GATED_TYPES = new Set(['feat', 'fix']);

/**
 * A conventional-commit subject: `type(scope)!: summary`.
 *
 * Scope and the breaking-change `!` are both optional, so `feat!: …` and
 * `fix(api): …` both match. The type is lower-cased before comparison rather
 * than matched case-sensitively: `Fix: corrupt token` is a fix by any reading,
 * and failing to gate it because of a capital letter would be a hole opened by
 * a typo.
 */
const CONVENTIONAL_SUBJECT = /^([A-Za-z]+)(?:\([^)]*\))?(?:!)?:\s/;

/**
 * `git revert` writes `Revert "<the original subject>"`.
 *
 * Unwrapped rather than ignored, because reverting a `feat` is exactly as
 * visible to someone operating the system as the `feat` was, and the reverted
 * commit's own type is the best available signal of that. Nested reverts
 * (`Revert "Revert "feat: …""`) unwrap too, and land back on the original
 * type, which is the right answer for a re-application.
 *
 * Note that this cuts in a direction the check cannot distinguish and does not
 * need to: reverting a released feature calls for a new bullet, reverting an
 * unreleased one calls for deleting the bullet it added. Both edit
 * CHANGELOG.md, so both satisfy the gate, and which was correct is review's
 * business.
 */
const REVERT_SUBJECT = /^Revert\s+"(.+)"\s*$/;

/**
 * The conventional-commit type this subject declares, lower-cased, or null.
 */
export function commitType(subject) {
  let current = (subject ?? '').trim();

  // Bounded: a revert chain longer than this is not a thing that happens, and
  // an unbounded loop over attacker-supplied text is not a thing to write.
  for (let depth = 0; depth < 10; depth += 1) {
    const match = CONVENTIONAL_SUBJECT.exec(current);
    if (match) return match[1].toLowerCase();

    const revert = REVERT_SUBJECT.exec(current);
    if (!revert) return null;
    current = revert[1].trim();
  }

  return null;
}

/**
 * The commits in the pull request that oblige a changelog entry.
 *
 * Merge commits are skipped, on the same reasoning
 * scripts/check-provenance.mjs skips them: their subject is generated by
 * GitHub and their author is whoever pressed the button. `Merge pull request
 * #14 from owner/fix/thing` is not a fix; it is a merge of one.
 *
 * The caller is expected to have walked the range with `firstParent: true` —
 * see the note in main().
 */
export function gatedCommits(commits) {
  return commits.filter(
    (commit) =>
      commit.parents.length <= 1 && GATED_TYPES.has(commitType(commit.subject)),
  );
}

function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i += 2)
    args[argv[i].replace(/^--/, '')] = argv[i + 1];
  return args;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const { base, head } = args;

  if (!base || !head) {
    console.error(
      '✗ Changelog check could not run.\n' +
        '  Both --base and --head are required:\n' +
        '    node scripts/check-changelog.mjs --base <sha> --head <sha>',
    );
    process.exit(1);
  }

  let commits;
  let files;
  try {
    // `--first-parent`, and this is the decision most likely to be revisited,
    // so: `base..head` on a pull-request branch can contain merges of `main`
    // that carry OTHER people's `feat` commits. Walking all parents would
    // attribute those to this pull request and demand a changelog entry for
    // work that already shipped with one — a false positive on an innocent
    // branch, and a check that fires on innocent branches is a check that gets
    // switched off. First-parent walks only the branch's own line of
    // development.
    //
    // The cost is a false NEGATIVE: a `feat` merged in from another topic
    // branch (not `main`) is not seen. That is the right way to be wrong. The
    // absorbed branch faced this same gate on its own pull request, and a
    // missed entry is a stale line in a file, while a false positive is a
    // blocked merge somebody has to work around.
    commits = commitsBetween(base, head, { firstParent: true });
    files = changedFiles(base, head);
  } catch (error) {
    // Loudly, never silently. An unreadable range means the answer is unknown,
    // and "unknown" must not render as a green check. In CI this most often
    // means the clone was shallow — actions/checkout needs `fetch-depth: 0`
    // for `base` to exist at all.
    console.error(
      `✗ Changelog check could not read ${base}..${head}:\n` +
        `  ${error.message.trim()}\n\n` +
        '  This is a failure, not a pass: the check cannot tell whether an\n' +
        '  entry was required. If this is CI, confirm actions/checkout ran\n' +
        '  with fetch-depth: 0.',
    );
    process.exit(1);
  }

  if (commits.length === 0) {
    // A determinate answer, not an indeterminate one: no commits, so nothing
    // obliges an entry. Printed rather than passed over in silence, because a
    // range that is unexpectedly empty is worth seeing in the log.
    console.log(`✓ Changelog check passed (no commits in ${base}..${head}).`);
    return;
  }

  const gated = gatedCommits(commits);
  if (gated.length === 0) {
    console.log(
      `✓ Changelog check passed (no feat/fix commits in ${commits.length} commit${
        commits.length === 1 ? '' : 's'
      }).`,
    );
    return;
  }

  if (files.includes(CHANGELOG)) {
    console.log(
      `✓ Changelog check passed (${gated.length} feat/fix commit${
        gated.length === 1 ? '' : 's'
      }, and ${CHANGELOG} is in the diff).`,
    );
    return;
  }

  console.error(
    `✗ Changelog check failed: this pull request ships a feat or a fix and does not touch ${CHANGELOG}.\n`,
  );
  for (const commit of gated) {
    console.error(`    ${commit.sha.slice(0, 9)} ${commit.subject}`);
  }
  console.error(
    `\n  Add a bullet to ${CHANGELOG} under \`## [Unreleased]\`, in the\n` +
      '  Keep-a-Changelog section that fits (Added / Changed / Fixed /\n' +
      '  Removed / Deprecated / Security) and under the VISION.MD §12 phase\n' +
      '  the change belongs to. Say what the change means for someone\n' +
      '  operating the system, and cite the issue number.\n\n' +
      '  There is no opt-out, by design. If this change genuinely warrants no\n' +
      '  changelog line, it is not a feat or a fix — it is a chore, a\n' +
      '  refactor, a test or a docs change, and retyping the commit is the\n' +
      '  supported way to say so.\n\n' +
      `  This check only verifies that ${CHANGELOG} is in the diff. Whether\n` +
      '  the entry is any good is for review; it is not mechanisable, and\n' +
      '  this check does not claim to have looked.',
  );
  process.exit(1);
}

// Only run when invoked directly, so tests can import the pure functions.
if (process.argv[1] === fileURLToPath(import.meta.url)) main();
